-- One-time Snowflake setup for the Supply Chain Data Warehouse.
-- Run as ACCOUNTADMIN (or SYSADMIN + SECURITYADMIN). Idempotent.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS SCDW_LOADER COMMENT = 'Airflow pipeline: loads RAW, builds STAGING/CORE/MART';
CREATE ROLE IF NOT EXISTS SCDW_REPORTER COMMENT = 'Power BI: read-only on MART';
GRANT ROLE SCDW_LOADER TO ROLE SYSADMIN;
GRANT ROLE SCDW_REPORTER TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS SVC_SCDW_AIRFLOW
    DEFAULT_ROLE = SCDW_LOADER
    DEFAULT_WAREHOUSE = SCDW_WH
    TYPE = SERVICE
    COMMENT = 'Airflow service user - authenticate with key pair (ALTER USER ... SET RSA_PUBLIC_KEY)';
CREATE USER IF NOT EXISTS SVC_SCDW_POWERBI
    DEFAULT_ROLE = SCDW_REPORTER
    DEFAULT_WAREHOUSE = SCDW_BI_WH
    TYPE = SERVICE
    COMMENT = 'Power BI gateway / service connection';
GRANT ROLE SCDW_LOADER TO USER SVC_SCDW_AIRFLOW;
GRANT ROLE SCDW_REPORTER TO USER SVC_SCDW_POWERBI;

USE ROLE SYSADMIN;

-- Separate warehouses so dashboard queries never queue behind the nightly load.
CREATE WAREHOUSE IF NOT EXISTS SCDW_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS SCDW_BI_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS SUPPLY_CHAIN_DW;
USE DATABASE SUPPLY_CHAIN_DW;

CREATE SCHEMA IF NOT EXISTS RAW COMMENT = 'Landing: source columns as VARCHAR + load metadata';
CREATE SCHEMA IF NOT EXISTS STAGING COMMENT = 'Typed, validated, de-duplicated';
CREATE SCHEMA IF NOT EXISTS CORE COMMENT = 'Star schema: dimensions and facts';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'KPI views consumed by Power BI';
CREATE SCHEMA IF NOT EXISTS AUDIT COMMENT = 'Load log and data-quality results';

CREATE FILE FORMAT IF NOT EXISTS RAW.SCDW_CSV
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    ENCODING = 'UTF8';

-- Internal stage for PUT from Airflow. For S3/Azure drops replace with an external stage + storage integration.
CREATE STAGE IF NOT EXISTS RAW.SCDW_LANDING
    FILE_FORMAT = RAW.SCDW_CSV
    COMMENT = 'Landing area for source extracts, one folder per batch';

-- Loader: full control of the pipeline schemas.
GRANT USAGE ON WAREHOUSE SCDW_WH TO ROLE SCDW_LOADER;
GRANT USAGE ON DATABASE SUPPLY_CHAIN_DW TO ROLE SCDW_LOADER;
GRANT ALL ON SCHEMA SUPPLY_CHAIN_DW.RAW TO ROLE SCDW_LOADER;
GRANT ALL ON SCHEMA SUPPLY_CHAIN_DW.STAGING TO ROLE SCDW_LOADER;
GRANT ALL ON SCHEMA SUPPLY_CHAIN_DW.CORE TO ROLE SCDW_LOADER;
GRANT ALL ON SCHEMA SUPPLY_CHAIN_DW.MART TO ROLE SCDW_LOADER;
GRANT ALL ON SCHEMA SUPPLY_CHAIN_DW.AUDIT TO ROLE SCDW_LOADER;
GRANT USAGE ON FILE FORMAT SUPPLY_CHAIN_DW.RAW.SCDW_CSV TO ROLE SCDW_LOADER;
GRANT READ, WRITE ON STAGE SUPPLY_CHAIN_DW.RAW.SCDW_LANDING TO ROLE SCDW_LOADER;

-- Reporter: MART only, including views created by future pipeline runs.
GRANT USAGE ON WAREHOUSE SCDW_BI_WH TO ROLE SCDW_REPORTER;
GRANT USAGE ON DATABASE SUPPLY_CHAIN_DW TO ROLE SCDW_REPORTER;
GRANT USAGE ON SCHEMA SUPPLY_CHAIN_DW.MART TO ROLE SCDW_REPORTER;
GRANT SELECT ON ALL VIEWS IN SCHEMA SUPPLY_CHAIN_DW.MART TO ROLE SCDW_REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SUPPLY_CHAIN_DW.MART TO ROLE SCDW_REPORTER;
-- MART views read CORE/AUDIT tables; owner's rights views mean the reporter needs no grants there.

-- Cost guardrail.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS SCDW_MONTHLY_QUOTA
    WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE SCDW_WH SET RESOURCE_MONITOR = SCDW_MONTHLY_QUOTA;
ALTER WAREHOUSE SCDW_BI_WH SET RESOURCE_MONITOR = SCDW_MONTHLY_QUOTA;
